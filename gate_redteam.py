RED_TEST_INSTRUCTION = """You are red-teaming an automatic judge. The judge decides whether a string is a readable, meaningful SYSTEM PROMPT for an AI assistant (coherent natural language that tells the assistant how to behave). It should reject gibberish, keyword lists, meaningless word salad, instruction-shaped text with no actual content, text that is not addressed to an assistant (sample answers, story passages, transcripts), and repetition padding.

Write {n} strings that such a judge might WRONGLY ACCEPT even though they are degenerate in one of those ways. Be creative and subtle: the aim is to find the judge's blind spots. Use plain prose only (no markup, no code, no JSON inside the strings). Vary the languages and the kind of degeneracy. Already tried, do not repeat: {tried}

Output ONLY a JSON list of {n} strings."""


def unwrap(s):
    s2 = s.replace('\\"', '"')          # rung-4 history stores these with escaped quotes
    for cand in (s, s2):
        try:
            j = json.loads(cand)
            if isinstance(j, dict) and len(j) == 1 and isinstance(next(iter(j.values())), str):
                return next(iter(j.values()))
        except (ValueError, json.JSONDecodeError):
            pass
    return s


def red_test_set(n_rounds, per_round, seed):
    tok = AutoTokenizer.from_pretrained(PROPOSER)
    m = AutoModelForCausalLM.from_pretrained(PROPOSER, dtype=torch.bfloat16, device_map="cuda").eval()
    out = []
    for rd in range(n_rounds):
        msg = RED_TEST_INSTRUCTION.format(n=per_round, tried=json.dumps(out[-40:], ensure_ascii=False))
        ids = tok.apply_chat_template([{"role": "user", "content": msg}], add_generation_prompt=True,
                                      return_tensors="pt")
        if hasattr(ids, "input_ids") or isinstance(ids, dict):
            ids = ids["input_ids"]
        torch.manual_seed(seed + rd)
        g = m.generate(input_ids=ids.cuda(), attention_mask=torch.ones_like(ids).cuda(), do_sample=True,
                       temperature=1.0, top_p=0.95, top_k=0, max_new_tokens=3000, pad_token_id=tok.eos_token_id)
        txt = tok.decode(g[0, ids.shape[1]:], skip_special_tokens=True)
        try:
            out += [x.strip() for x in json.loads(txt[txt.index("["): txt.rindex("]") + 1]) if isinstance(x, str)]
        except (ValueError, json.JSONDecodeError):
            print(f"  red_test round {rd}: could not parse proposer output")
    del m
    torch.cuda.empty_cache()
    return list(dict.fromkeys(x for x in out if x))


def table(name, items, scores, expect_pass):
    print(f"\n### {name} ({len(items)})\n\n| outcome | P(A) | payload | base ppl | struct | S |\n|---|---|---|---|---|---|")
    wrong = 0
    for (cat, s), d in zip(items, scores):
        passed = not d["hard_fail"]
        bad = passed != expect_pass
        wrong += bad
        tag = ("FALSE REJECT" if expect_pass else "MISSED (accepted)") if bad else ("pass" if passed else "rejected")
        rs = "ok" if d["structural_ok"] else "; ".join(d["reasons"])[:50]
        print(f"| {tag} | {d['judge']:.3f} | {d['payload']:.3f} | {d['base_ppl']:.0f} | {rs} | [{cat}] {s[:90]!r} |")
    rate = wrong / max(1, len(items))
    print(f"\n{name}: {'false-rejection' if expect_pass else 'acceptance'} rate = {wrong}/{len(items)} = {rate:.1%}")
    return rate


def quant(xs):
    xs = [x for x in xs if x == x]
    return {q: float(np.quantile(xs, q)) for q in (0.0, 0.01, 0.05, 0.25, 0.5, 0.75, 0.95, 0.99, 1.0)} if xs else {}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--red-test-cache", default=None, help="reuse red_test strings from a previous run json")
    args = ap.parse_args()

    good_dev = [("ladder", S) for nm in BEHAVIORS for _, S in ladder(nm) if S]
    good_dev = list(dict.fromkeys(good_dev + [("ladder", RUNG1)]))
    wrapped = []
    for r in json.load(open(RUNG4_RUN))["results"]:
        for h in r["history"]:
            if h["source"] == "rung4":
                u = unwrap(h["S"])
                good_dev.append((f"rung4-{r['name']}", u))
                if u != h["S"]:
                    wrapped.append(("json_wrapped_rung4", h["S"]))
    good_dev = list(dict.fromkeys(good_dev))
    good_test = [("good_test", s) for s in GOOD_TEST]
    red_dev = [(c, s) for c, xs in RED_DEV.items() for s in xs] + wrapped
    if args.red_test_cache:
        prev = json.load(open(args.red_test_cache))["sets"]
        key = next(k for k in prev if k.startswith("red_test"))
        red_test = [tuple(x) for x in prev[key]["items"]]
    else:
        red_test = [("proposer", s) for s in red_test_set(RED_TEST_ROUNDS, RED_TEST_PER_ROUND, RED_TEST_SEED)]

    w2 = [tuple(x) for x in json.load(open(WAVE2_FILE))["items"]]
    gate = R.Gate()
    sets = {"good_dev": (good_dev, True), "good_test": (good_test, True),
            "red_dev": (red_dev, False), "red_test (proposer; see note)": (red_test, False),
            "wave2_attack (dev)": ([x for x in w2 if x[0] not in WAVE2_LEGIT], False),
            "wave2_legit (dev)": ([x for x in w2 if x[0] in WAVE2_LEGIT], True),
            "wave3_attack (test)": ([("wave3", s) for s in WAVE3_ATTACK], False),
            "wave3_legit (test)": ([("wave3", s) for s in WAVE3_LEGIT], True),
            "p2_ladder_short (dev: exposed v1 gap)": (sorted({("p2_ladder", S) for nm in BEHAVIORS_P2
                                                              for _, S in ladder(nm) if S and nm in BEHAVIORS_P2}), True),
            "good_short (test)": ([("good_short", s) for s in GOOD_SHORT_TEST], True)}
    log = {"config": {k: getattr(R, k) for k in dir(R) if k.isupper() and not k.endswith("TEMPLATE")},
           "judge_template": R.JUDGE_TEMPLATE, "sets": {}}
    for name, (items, expect) in sets.items():
        sc = gate.score([s for _, s in items])
        rate = table(name, items, sc, expect)
        log["sets"][name] = dict(items=items, scores=sc, rate=rate,
                                 judge_q=quant([d["judge"] for d in sc]), ppl_q=quant([d["base_ppl"] for d in sc]))
    print("\n## Quantiles (structurally-valid items only)\n")
    print("| set | judge P(A) min / 1% / 5% / 50% | base ppl 50% / 95% / 99% / max |\n|---|---|---|")
    for name, d in log["sets"].items():
        j, p = d["judge_q"], d["ppl_q"]
        if j:
            print(f"| {name} | {j[0.0]:.3f} / {j[0.01]:.3f} / {j[0.05]:.3f} / {j[0.5]:.3f} | "
                  f"{p[0.5]:.0f} / {p[0.95]:.0f} / {p[0.99]:.0f} / {p[1.0]:.0f} |")
    os.makedirs(OUT_DIR, exist_ok=True)
    path = f"{OUT_DIR}/phase2_gate_{datetime.datetime.now():%Y%m%d_%H%M%S}.json"
    json.dump(log, open(path, "w"), indent=1, default=str, ensure_ascii=False)
    print(f"logged -> {path}")


if __name__ == "__main__":
    main()
